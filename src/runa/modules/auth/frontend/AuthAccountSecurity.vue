<script setup lang="ts">
import { actionIcons, withTableFilters } from '@/runa/ui';
import { trustedDeviceColumns } from './trustedDeviceColumns';
import { computed, ref, watch, onScopeDispose } from 'vue';
import {
  Accordion,
  Button,
  Card,
  Dialog,
  ConfirmDialog,
  Form,
  FormNotifications,
  Table,
  TextInput,
} from '@/runa/ui';
import type { TableColumn, TableQuery } from '@/runa/ui';
import type { AccountRow } from './account';
import type { useAuthAccount } from './useAuthAccount';
import AuthTotpSetup from './AuthTotpSetup.vue';
const props = defineProps<{ account: ReturnType<typeof useAuthAccount> }>();
const emit = defineEmits<{ 'feedback-modal': [active: boolean] }>();
const {
  text,
  locale,
  security,
  busy,
  target,
  secret,
  qrCode,
  codes,
  overviewAction,
  sectionFields,
  sectionErrors,
  saveSection,
  failure,
  failureText,
  notice,
  canTrustDevice,
  trustedRows,
  trustedLoading,
  trustedLoaded,
  trustedCursor,
  loadTrustedDevices,
  revokeTrustedDevice,
} = props.account;
async function exportRows(signal: AbortSignal) {
  await props.account.authorizeTableExport(signal);
  return trustedRows.value;
}
const devicesExpanded = ref(false);
const modal = ref<'factor' | null>(null);
const removing = ref<string>();
const attempt = ref(0);
const securityForm = ref<{ focusInvalid: () => void }>();
const query = ref<TableQuery>({ page: 1, perPage: 5, sort: null, filters: {} });
watch(
  () => modal.value !== null || Boolean(removing.value),
  (value) => emit('feedback-modal', value),
);
function clearDraft() {
  overviewAction.value = 'none';
  secret.value = '';
  qrCode.value = '';
  for (const key of Object.keys(sectionFields.security))
    sectionFields.security[key] = '';
  for (const key of Object.keys(sectionErrors.security))
    delete sectionErrors.security[key];
  const errors = props.account.errors;
  for (const key of ['enrollment_code']) delete errors[key];
}
onScopeDispose(() => {
  clearDraft();
  emit('feedback-modal', false);
});
const actions = computed(() => [
  { value: 'none', label: text('Bez zmian', 'No change') },
  ...(canTrustDevice.value
    ? [
        {
          value: 'trustIssue',
          label: text('Zaufaj tej przeglądarce', 'Trust this browser'),
        },
      ]
    : []),
  ...(security.value?.totp_enabled && secret.value
    ? [
        {
          value: 'totpConfirm',
          label: text('Potwierdź aplikację', 'Confirm authenticator'),
        },
      ]
    : []),
  ...(security.value?.totp_enabled &&
  !security.value.enrolled.includes('totp') &&
  !secret.value
    ? [
        {
          value: 'totpBegin',
          label: text(
            'Włącz aplikację uwierzytelniającą',
            'Enable authenticator app',
          ),
        },
      ]
    : []),
  ...(security.value?.email_otp_enabled &&
  security.value.email_verified &&
  !security.value.enrolled.includes('email')
    ? [
        {
          value: 'emailEnable',
          label: text('Włącz kody e-mail', 'Enable email codes'),
        },
      ]
    : []),
  ...(security.value?.enrolled.length
    ? [{ value: 'disable', label: text('Wyłącz metodę', 'Disable method') }]
    : []),
  ...(security.value?.totp_enabled &&
  security.value.recovery_codes_enabled &&
  security.value.enrolled.includes('totp')
    ? [
        {
          value: 'recoveryRotate',
          label: text(
            'Wygeneruj nowe kody odzyskiwania',
            'Replace recovery codes',
          ),
        },
      ]
    : []),
]);

const methods = computed(() => [
  ...(security.value?.totp_enabled
    ? [
        {
          value: 'totp',
          label: text('Aplikacja uwierzytelniająca', 'Authenticator app'),
          description: text(
            'Kody jednorazowe generowane w aplikacji na telefonie.',
            'One-time codes generated by an app on your phone.',
          ),
          enrolled: security.value.enrolled.includes('totp'),
          available: true,
        },
      ]
    : []),
  ...(security.value?.email_otp_enabled
    ? [
        {
          value: 'email',
          label: text('Kody e-mail', 'Email codes'),
          description: security.value.email_verified
            ? text(
                'Kody wysyłane na główny, potwierdzony adres e-mail.',
                'Codes sent to your verified primary email address.',
              )
            : text(
                'Najpierw potwierdź swój główny adres e-mail.',
                'Verify your primary email address first.',
              ),
          enrolled: security.value.enrolled.includes('email'),
          available:
            security.value.enrolled.includes('email') ||
            security.value.email_verified,
        },
      ]
    : []),
]);
const operationLabel = computed(() =>
  overviewAction.value === 'disable'
    ? text('Wyłącz metodę: ', 'Disable method: ') +
      (target.value === 'totp' ? text('aplikacja', 'authenticator') : 'e-mail')
    : (actions.value.find((action) => action.value === overviewAction.value)
        ?.label ?? ''),
);
watch([actions, methods, () => security.value?.trusted_devices_enabled], () => {
  if (
    overviewAction.value !== 'none' &&
    ((!(
      (overviewAction.value === 'totpBegin' ||
        overviewAction.value === 'totpConfirm') &&
      secret.value &&
      security.value?.totp_enabled
    ) &&
      !actions.value.some((action) => action.value === overviewAction.value)) ||
      (overviewAction.value === 'disable' &&
        !methods.value.some((candidate) => candidate.value === target.value)))
  ) {
    modal.value = null;
    clearDraft();
  }
});
function selectMethod(value: string, enrolled: boolean) {
  setAction(
    enrolled ? 'disable' : value === 'totp' ? 'totpBegin' : 'emailEnable',
  );
  target.value = value;
}
function setAction(value: string) {
  if (busy.value) return;
  if (!actions.value.some((action) => action.value === value)) return;
  overviewAction.value = value as typeof overviewAction.value;
  modal.value = value === 'none' ? null : 'factor';
  attempt.value = 0;
  failure.value = '';
  notice.value = '';
  qrCode.value = '';
  target.value = security.value?.enrolled[0] ?? 'totp';
  if (value !== 'totpConfirm') secret.value = '';
  sectionFields.security.enrollment_code = '';
  Object.keys(sectionErrors.security).forEach(
    (key) => delete sectionErrors.security[key],
  );
}

function close(value: boolean) {
  if (value || busy.value) return;
  clearDraft();
  failure.value = '';
  notice.value = '';
  modal.value = null;
  removing.value = undefined;
}
async function save() {
  if (busy.value) return;
  attempt.value++;
  const activeForm = props.account.form;
  activeForm.value = securityForm.value;
  await saveSection('security');
  if (
    !failure.value &&
    !Object.keys(sectionErrors.security).length &&
    overviewAction.value === 'none'
  ) {
    modal.value = null;
    clearDraft();
  }
}
async function removeDevice() {
  if (!removing.value || busy.value) return;
  attempt.value++;
  if (await revokeTrustedDevice(removing.value)) removing.value = undefined;
}
const columns = computed<TableColumn<AccountRow>[]>(() =>
  withTableFilters(
    trustedDeviceColumns<AccountRow>(locale.value, (row, key) => row[key]),
  ),
);
watch(
  () => security.value?.trusted_devices_enabled,
  (enabled) => {
    if (!enabled) {
      devicesExpanded.value = false;
      removing.value = undefined;
    }
  },
);
</script>
<template>
  <Card
    v-if="methods.length || security?.trusted_devices_enabled"
    data-account-security
  >
    <template #header
      ><h3>
        {{
          methods.length
            ? text('Uwierzytelnianie dwuetapowe', 'Two-factor authentication')
            : text('Zaufane urządzenia', 'Trusted devices')
        }}
      </h3></template
    >
    <div class="space-y-4">
      <div class="divide-y divide-[var(--runa-border)]">
        <div
          v-for="securityMethod in methods"
          :key="securityMethod.value"
          class="flex flex-wrap items-center justify-between gap-3 py-4 first:pt-0 last:pb-0"
        >
          <div class="min-w-0 space-y-1">
            <h4 class="text-sm font-semibold">{{ securityMethod.label }}</h4>
            <p class="text-xs text-muted">{{ securityMethod.description }}</p>
          </div>
          <Button
            :icon="securityMethod.enrolled ? 'shield-x' : 'shield-check'"
            :intent="securityMethod.enrolled ? 'danger' : 'commit'"
            variant="outline"
            :disabled="busy || modal !== null || !securityMethod.available"
            @click="selectMethod(securityMethod.value, securityMethod.enrolled)"
            >{{
              securityMethod.enrolled
                ? text('Wyłącz', 'Disable')
                : text('Skonfiguruj', 'Set up')
            }}</Button
          >
        </div>
      </div>
      <Button
        v-if="
          security?.totp_enabled &&
          security.recovery_codes_enabled &&
          security.enrolled.includes('totp')
        "
        icon="rotate-2"
        intent="caution"
        variant="outline"
        :disabled="busy || modal !== null"
        @click="setAction('recoveryRotate')"
        >{{
          text('Wygeneruj nowe kody odzyskiwania', 'Replace recovery codes')
        }}</Button
      >

      <section
        v-if="security?.trusted_devices_enabled"
        class="space-y-3"
        :class="methods.length ? 'border-t border-line pt-4' : ''"
        data-trusted-devices
      >
        <p v-if="!canTrustDevice" class="text-xs text-muted">
          {{
            text(
              'Najpierw włącz uwierzytelnianie dwuetapowe, aby zaufać tej przeglądarce.',
              'Enable two-factor authentication before trusting this browser.',
            )
          }}
        </p>
        <div class="flex flex-wrap gap-2">
          <Button
            :icon="actionIcons.trust"
            intent="commit"
            variant="outline"
            :disabled="busy || !canTrustDevice"
            @click="setAction('trustIssue')"
            >{{ text('Zaufaj tej przeglądarce', 'Trust this browser') }}</Button
          >
        </div>
        <Accordion
          v-model="devicesExpanded"
          :label="text('Zaufane urządzenia', 'Trusted devices')"
        >
          <div class="space-y-3">
            <Table
              v-model:query="query"
              :export-allowed="account.tableExportAllowed?.value === true"
              :export-rows="exportRows"
              :refresh="
                async () => {
                  await loadTrustedDevices();
                }
              "
              :refresh-disabled="busy"
              mode="client"
              :rows="trustedRows"
              :loading="trustedLoading && !trustedLoaded"
              :refreshing="trustedLoading"
              :retain-empty-frame="true"
              :columns="columns"
              :row-key="(row) => row.public_id"
              :caption="text('Zaufane urządzenia', 'Trusted devices')"
              :english="locale === 'en'"
            >
              <template #actions="{ row }"
                ><Button
                  :icon="actionIcons.revoke"
                  intent="danger"
                  size="sm"
                  variant="outline"
                  :disabled="busy"
                  @click="
                    removing = row.public_id;
                    attempt = 0;
                  "
                  >{{ text('Unieważnij', 'Revoke') }}</Button
                ></template
              >
            </Table>
            <Button
              v-if="trustedCursor"
              :icon="actionIcons.load"
              intent="inspect"
              :busy="trustedLoading"
              :disabled="busy"
              @click="loadTrustedDevices(true)"
              >{{ text('Wczytaj starsze', 'Load older') }}</Button
            >
          </div>
        </Accordion>
      </section>
    </div>
  </Card>
  <Dialog
    :model-value="modal !== null && !codes.length"
    :title="operationLabel"
    :locale="locale"
    size="md"
    :busy="busy"
    initial-focus="input"
    @update:model-value="close"
  >
    <Form
      v-if="modal === 'factor'"
      ref="securityForm"
      data-account-section="security"
      :label="operationLabel"
      :busy="busy"
      @submit="save"
    >
      <div
        v-if="secret && overviewAction === 'totpConfirm'"
        class="space-y-3 border-l-2 border-[var(--runa-primary-solid)] pl-4"
      >
        <AuthTotpSetup :secret="secret" :qr-code="qrCode" :locale="locale" />
        <TextInput
          :model-value="sectionFields.security.enrollment_code ?? ''"
          name="enrollment_code"
          autocomplete="one-time-code"
          inputmode="numeric"
          :label="text('Kod z aplikacji', 'Authenticator code')"
          required
          :error="sectionErrors.security.enrollment_code ?? ''"
          @update:model-value="
            sectionFields.security.enrollment_code = $event ?? '';
            delete sectionErrors.security.enrollment_code;
          "
        />
      </div>

      <template #actions>
        <Button
          :icon="actionIcons.confirm"
          :intent="
            overviewAction === 'disable'
              ? 'danger'
              : overviewAction === 'recoveryRotate'
                ? 'caution'
                : 'commit'
          "
          type="submit"
          variant="outline"
          :busy="busy"
          :disabled="overviewAction === 'trustIssue' && !canTrustDevice"
          >{{ operationLabel }}</Button
        >
        <Button
          :icon="actionIcons.cancel"
          intent="cancel"
          :disabled="busy"
          @click="close(false)"
          >{{ text('Anuluj', 'Cancel') }}</Button
        >
      </template>
    </Form>
    <FormNotifications
      v-if="modal && !removing"
      :attempt="attempt"
      :error="failure ? failureText : ''"
      :success="notice"
      :invalid="Object.keys(sectionErrors.security).length > 0"
      :locale="locale"
    >
      <template #actions
        ><Button
          v-if="failure === 'csrf'"
          :icon="actionIcons.refresh"
          intent="inspect"
          :busy="busy"
          @click="account.refreshCsrf"
          >{{ text('Odśwież zabezpieczenie', 'Renew form security') }}</Button
        ></template
      >
    </FormNotifications>
  </Dialog>
  <ConfirmDialog
    :model-value="Boolean(removing)"
    :title="text('Unieważnić zaufanie?', 'Revoke device trust?')"
    :confirm-label="text('Unieważnij', 'Revoke')"
    confirm-intent="danger"
    confirm-icon="shield-x"
    :locale="locale"
    :busy="busy"
    @update:model-value="
      (value) => {
        if (!value && !busy) removing = undefined;
      }
    "
    @confirm="removeDevice"
  >
    <p class="text-sm leading-7">
      {{
        text(
          'Przy kolejnym logowaniu na tym urządzeniu będzie wymagany kod weryfikacyjny.',
          'The next sign-in on this device will require a verification code.',
        )
      }}
    </p>
    <FormNotifications
      v-if="removing && attempt"
      :attempt="attempt"
      :error="failure ? failureText : ''"
      :locale="locale"
    >
      <template #actions
        ><Button
          v-if="failure === 'csrf'"
          :icon="actionIcons.refresh"
          intent="inspect"
          :busy="busy"
          @click="account.refreshCsrf"
          >{{ text('Odśwież zabezpieczenie', 'Renew form security') }}</Button
        ></template
      >
    </FormNotifications>
  </ConfirmDialog>
</template>
