<script setup lang="ts">
import { computed, ref, watch, onScopeDispose } from 'vue';
import {
  Avatar,
  Button,
  Card,
  Dialog,
  ConfirmDialog,
  FileInput,
  Form,
  FormNotifications,
  RadioGroup,
  TextInput,
} from '@/runa/ui';
import type { AccountSection, useAuthAccount } from './useAuthAccount';
import AuthAccountProof from './AuthAccountProof.vue';
import AuthAvatarCropper from './AuthAvatarCropper.vue';
import AuthTotpSetup from './AuthTotpSetup.vue';
const props = defineProps<{
  account: ReturnType<typeof useAuthAccount>;
  passwordHint: string;
}>();
const emit = defineEmits<{ 'feedback-modal': [active: boolean] }>();
const {
  text,
  locale,
  profile,
  security,
  options,
  busy,
  fields,
  naming,
  target,
  secret,
  qrCode,
  codes,
  files,
  has,
  canAvatar,
  overviewAction,
  removeAvatar,
  sectionFields,
  sectionErrors,
  saveSection,
  sendVerification,
  failure,
  failureText,
  notice,
} = props.account;
const detailForm = ref<{ focusInvalid: () => void }>();
const avatarForm = ref<{ focusInvalid: () => void }>();
const passwordForm = ref<{ focusInvalid: () => void }>();
const securityForm = ref<{ focusInvalid: () => void }>();
const originals = ref<readonly File[]>([]);
const cropOpen = ref(false);
const removeOpen = ref(false);
const removalAttempt = ref(0);
watch(removeOpen, (value) => {
  if (value) removalAttempt.value = 0;
  emit('feedback-modal', value);
});
onScopeDispose(() => emit('feedback-modal', false));
const previewUrl = ref('');
function clearPreview() {
  if (previewUrl.value) URL.revokeObjectURL(previewUrl.value);
  previewUrl.value = '';
}
watch(originals, (value) => {
  cropError.value = '';
  cropReady.value = false;
  if (value[0]) cropOpen.value = true;
  else {
    cropOpen.value = false;
    files.value = [];
    clearPreview();
  }
});
onScopeDispose(clearPreview);
const cropper = ref<InstanceType<typeof AuthAvatarCropper>>();
const cropReady = ref(false),
  cropError = ref(''),
  cropping = ref(false);
const identityFields = computed(() => [
  ...(has('own_name_editable')
    ? naming.value === 'single'
      ? ['name']
      : ['first_name', 'surname']
    : []),
  ...(has('own_login_editable') ? ['login'] : []),
]);
const labels = computed<Record<string, string>>(() => ({
  name: text('Nazwa wyświetlana', 'Display name'),
  first_name: text('Imię', 'First name'),
  surname: text('Nazwisko', 'Surname'),
  login: 'Login',
  password: text('Nowe hasło', 'New password'),
  password_confirmation: text('Powtórz nowe hasło', 'Repeat new password'),
}));
const actions = computed(() => [
  { value: 'none', label: text('Bez zmian', 'No change') },
  ...(secret.value
    ? [
        {
          value: 'totpConfirm',
          label: text('Potwierdź aplikację', 'Confirm authenticator'),
        },
      ]
    : []),
  ...(security.value?.totp_enabled &&
  !security.value.enrolled.includes('totp') &&
  !secret.value
    ? [
        {
          value: 'totpBegin',
          label: text(
            'Włącz aplikację uwierzytelniającą',
            'Enable authenticator app',
          ),
        },
      ]
    : []),
  ...(security.value?.email_otp_enabled &&
  security.value.email_verified &&
  !security.value.enrolled.includes('email')
    ? [
        {
          value: 'emailEnable',
          label: text('Włącz kody e-mail', 'Enable email codes'),
        },
      ]
    : []),
  ...(security.value?.enrolled.length
    ? [{ value: 'disable', label: text('Wyłącz metodę', 'Disable method') }]
    : []),
  ...(security.value?.recovery_codes_enabled &&
  security.value.enrolled.includes('totp')
    ? [
        {
          value: 'recoveryRotate',
          label: text(
            'Wygeneruj nowe kody odzyskiwania',
            'Replace recovery codes',
          ),
        },
      ]
    : []),
]);

const methods = computed(() => [
  ...(security.value?.totp_enabled || security.value?.enrolled.includes('totp')
    ? [
        {
          value: 'totp',
          label: text('Aplikacja uwierzytelniająca', 'Authenticator app'),
          description: text(
            'Kody jednorazowe generowane w aplikacji na telefonie.',
            'One-time codes generated by an app on your phone.',
          ),
          enrolled: security.value.enrolled.includes('totp'),
          available: true,
        },
      ]
    : []),
  ...(security.value?.email_otp_enabled ||
  security.value?.enrolled.includes('email')
    ? [
        {
          value: 'email',
          label: text('Kody e-mail', 'Email codes'),
          description: security.value.email_verified
            ? text(
                'Kody wysyłane na główny, potwierdzony adres e-mail.',
                'Codes sent to your verified primary email address.',
              )
            : text(
                'Najpierw potwierdź swój główny adres e-mail.',
                'Verify your primary email address first.',
              ),
          enrolled: security.value.enrolled.includes('email'),
          available:
            security.value.enrolled.includes('email') ||
            security.value.email_verified,
        },
      ]
    : []),
]);
const operationLabel = computed(() =>
  overviewAction.value === 'disable'
    ? text('Wyłącz metodę: ', 'Disable method: ') +
      (target.value === 'totp' ? text('aplikacja', 'authenticator') : 'e-mail')
    : (actions.value.find((action) => action.value === overviewAction.value)
        ?.label ?? ''),
);
function selectMethod(value: string, enrolled: boolean) {
  setAction(
    enrolled ? 'disable' : value === 'totp' ? 'totpBegin' : 'emailEnable',
  );
  target.value = value;
}
async function confirmRemoval() {
  if (busy.value || cropping.value || originals.value.length) return;
  removalAttempt.value++;
  removeAvatar.value = true;
  await save('avatar');
  removeAvatar.value = false;
  if (
    !failure.value &&
    !Object.keys(sectionErrors.avatar).length &&
    notice.value
  )
    removeOpen.value = false;
}
function setAction(value: string) {
  if (!actions.value.some((action) => action.value === value)) return;
  overviewAction.value = value as typeof overviewAction.value;
  target.value = security.value?.enrolled[0] ?? 'totp';
  if (value !== 'totpConfirm') secret.value = '';
  sectionFields.security.current_password = '';
  sectionFields.security.code = '';
  sectionFields.security.enrollment_code = '';
  Object.keys(sectionErrors.security).forEach(
    (key) => delete sectionErrors.security[key],
  );
}
async function save(section: AccountSection) {
  if (busy.value || cropping.value) return;
  props.account.form.value = {
    details: detailForm,
    avatar: avatarForm,
    password: passwordForm,
    security: securityForm,
  }[section].value;
  await saveSection(section);
  if (
    section === 'avatar' &&
    !failure.value &&
    !Object.keys(sectionErrors.avatar).length &&
    notice.value
  )
    originals.value = [];
}
async function applyCrop() {
  if (!cropper.value || !cropReady.value || cropping.value) return;
  cropError.value = '';
  cropping.value = true;
  try {
    const cropped = await cropper.value.crop();
    files.value = [cropped];
    clearPreview();
    previewUrl.value = URL.createObjectURL(cropped);
    removeAvatar.value = false;
    cropOpen.value = false;
  } catch {
    cropError.value = text(
      'Nie udało się przygotować zdjęcia. Wybierz inny plik.',
      'Could not prepare the image. Choose another file.',
    );
  } finally {
    cropping.value = false;
  }
}
function closeCrop(value: boolean) {
  if (cropping.value) return;
  cropOpen.value = value;
  if (!value && !files.value.length) originals.value = [];
}
</script>
<template>
  <div
    v-if="profile"
    class="grid min-w-0 items-start gap-6 xl:grid-cols-2"
    :inert="codes.length > 0 || undefined"
  >
    <div class="min-w-0 space-y-6">
      <Card>
        <template #header
          ><h3>{{ text('Dane konta', 'Account details') }}</h3></template
        >
        <Form
          ref="detailForm"
          data-account-section="details"
          :label="text('Dane konta', 'Account details')"
          :busy="busy"
          @submit="save('details')"
        >
          <RadioGroup
            v-if="has('own_name_editable')"
            v-model="naming"
            :label="text('Sposób prezentacji nazwy', 'Name format')"
            :options="[
              { value: 'single', label: text('Jedna nazwa', 'Single name') },
              {
                value: 'full',
                label: text('Imię i nazwisko', 'First name and surname'),
              },
            ]"
          />
          <div class="grid min-w-0 gap-5 md:grid-cols-2">
            <TextInput
              v-for="name in identityFields"
              :key="name"
              :model-value="fields[name] ?? ''"
              :name="name"
              :label="labels[name] ?? name"
              :required="
                name !== 'login' || options?.identifier_mode === 'login'
              "
              :error="sectionErrors.details[name] ?? ''"
              autocomplete="off"
              @update:model-value="
                fields[name] = $event ?? '';
                delete sectionErrors.details[name];
              "
            />
          </div>
          <p
            v-if="!has('own_name_editable')"
            class="text-sm [overflow-wrap:anywhere]"
          >
            {{ profile.display_name }}
          </p>
          <TextInput
            :model-value="fields.email ?? ''"
            name="email"
            type="email"
            autocomplete="email"
            :label="text('Adres e-mail', 'Email address')"
            :readonly="!has('own_email_editable')"
            required
            :error="sectionErrors.details.email ?? ''"
            :helper="
              profile.email_verified
                ? text(
                    'Adres potwierdzony. Zmiana wymaga potwierdzenia nowego adresu.',
                    'Address verified. Changing it requires verification of the new address.',
                  )
                : text('Adres niepotwierdzony.', 'Email not verified.')
            "
            @update:model-value="
              fields.email = $event ?? '';
              delete sectionErrors.details.email;
            "
          />
          <Button
            v-if="!profile.email_verified"
            :busy="busy"
            @click="sendVerification"
            >{{
              text('Wyślij wiadomość weryfikacyjną', 'Send verification email')
            }}</Button
          >
          <AuthAccountProof
            v-if="has('own_email_editable') && fields.email !== profile.email"
            :account="account"
            section="details"
          />
          <template #actions
            ><Button
              type="submit"
              variant="outline"
              :busy="busy"
              :disabled="
                !has('own_name_editable') &&
                !has('own_login_editable') &&
                !has('own_email_editable')
              "
              >{{ text('Zapisz dane', 'Save details') }}</Button
            ></template
          >
        </Form>
      </Card>
      <Card>
        <template #header
          ><h3>{{ text('Hasło', 'Password') }}</h3></template
        >
        <Form
          ref="passwordForm"
          data-account-section="password"
          :label="text('Zmiana hasła', 'Password change')"
          :busy="busy"
          @submit="save('password')"
        >
          <div class="grid min-w-0 gap-5 md:grid-cols-2">
            <TextInput
              v-for="name in ['password', 'password_confirmation']"
              :key="name"
              :model-value="sectionFields.password[name] ?? ''"
              :name="name"
              type="password"
              autocomplete="new-password"
              :label="labels[name] ?? name"
              required
              :error="sectionErrors.password[name] ?? ''"
              :helper="name === 'password' ? passwordHint : ''"
              @update:model-value="
                sectionFields.password[name] = $event ?? '';
                delete sectionErrors.password[name];
              "
            />
          </div>
          <AuthAccountProof :account="account" section="password" />
          <template #actions
            ><Button type="submit" variant="outline" :busy="busy">{{
              text('Zapisz hasło', 'Save password')
            }}</Button></template
          >
        </Form>
      </Card>
    </div>
    <div class="min-w-0 space-y-6">
      <Card v-if="has('avatar_enabled')">
        <template #header
          ><h3>{{ text('Zdjęcie profilowe', 'Profile image') }}</h3></template
        >
        <Form
          ref="avatarForm"
          data-account-section="avatar"
          :label="text('Zdjęcie profilowe', 'Profile image')"
          :busy="busy || cropping"
          @submit="save('avatar')"
        >
          <div class="flex items-center gap-4">
            <Avatar
              :src="
                previewUrl ||
                (profile.has_avatar
                  ? `/api/runa/auth/profile/avatar?v=${profile.version}`
                  : '')
              "
              :initials="profile.initials"
              :size="80"
              class="text-xl"
            />
            <p class="text-xs leading-relaxed text-muted">
              {{
                text(
                  'Wybierz zdjęcie do 20 MB, ustaw kadr i zapisz.',
                  'Choose an image up to 20 MB, adjust the crop and save.',
                )
              }}
            </p>
          </div>
          <template v-if="canAvatar">
            <FileInput
              v-model="originals"
              :locale="locale"
              :label="
                text('Obraz JPEG, PNG lub WebP', 'JPEG, PNG or WebP image')
              "
              accept="image/jpeg,image/png,image/webp"
              :max-bytes="20 * 1024 * 1024"
              :choose-label="text('Wybierz plik', 'Choose file')"
              :empty-label="text('Nie wybrano pliku', 'No file selected')"
              :remove-label="text('Usuń', 'Remove')"
              :count-message="text('Wybierz jeden plik.', 'Choose one file.')"
              :size-message="
                text('Plik przekracza 20 MB.', 'File exceeds 20 MB.')
              "
              :type-message="
                text(
                  'Wybierz obraz JPEG, PNG lub WebP.',
                  'Choose a JPEG, PNG or WebP image.',
                )
              "
              :error="sectionErrors.avatar.avatar ?? ''"
              @update:model-value="
                cropReady = false;
                cropError = '';
                delete sectionErrors.avatar.avatar;
              "
            />
            <Button
              v-if="originals[0] && files.length"
              @click="cropOpen = true"
              >{{ text('Popraw kadr', 'Adjust crop') }}</Button
            >
          </template>
          <template #actions
            ><Button
              type="submit"
              variant="outline"
              :busy="busy || cropping"
              :disabled="!canAvatar || (!files.length && !removeAvatar)"
              >{{ text('Zapisz zdjęcie', 'Save image') }}</Button
            >
            <Button
              v-if="canAvatar && profile.has_avatar"
              variant="outline"
              tone="danger"
              :disabled="busy || cropping || originals.length > 0"
              @click="removeOpen = true"
              >{{ text('Usuń avatar', 'Remove avatar') }}</Button
            ></template
          >
        </Form>
      </Card>
      <Card>
        <template #header
          ><h3>
            {{
              text('Uwierzytelnianie dwuetapowe', 'Two-factor authentication')
            }}
          </h3></template
        >
        <Form
          v-if="!codes.length"
          ref="securityForm"
          data-account-section="security"
          :label="
            text('Uwierzytelnianie dwuetapowe', 'Two-factor authentication')
          "
          :busy="busy"
          @submit="save('security')"
        >
          <p class="text-xs text-muted">
            {{ text('Włączone metody:', 'Enrolled methods:') }}
            {{
              security?.enrolled
                .map((value) =>
                  value === 'totp'
                    ? text('aplikacja', 'authenticator')
                    : 'e-mail',
                )
                .join(', ') || text('brak', 'none')
            }}
          </p>
          <div class="divide-y divide-[var(--runa-border)]">
            <div
              v-for="method in methods"
              :key="method.value"
              class="flex flex-wrap items-center justify-between gap-3 py-4 first:pt-0"
            >
              <div class="min-w-0 space-y-1">
                <h4 class="text-sm font-semibold">{{ method.label }}</h4>
                <p class="text-xs text-muted">{{ method.description }}</p>
                <p class="text-xs">
                  {{
                    method.enrolled
                      ? text('Włączona', 'Enabled')
                      : text('Wyłączona', 'Disabled')
                  }}
                </p>
              </div>
              <Button
                variant="outline"
                :tone="method.enrolled ? 'danger' : 'primary'"
                :disabled="
                  busy || overviewAction !== 'none' || !method.available
                "
                @click="selectMethod(method.value, method.enrolled)"
                >{{
                  method.enrolled
                    ? text('Wyłącz', 'Disable')
                    : text('Skonfiguruj', 'Set up')
                }}</Button
              >
            </div>
          </div>
          <Button
            v-if="
              security?.recovery_codes_enabled &&
              security.enrolled.includes('totp')
            "
            variant="outline"
            :disabled="busy || overviewAction !== 'none'"
            @click="setAction('recoveryRotate')"
            >{{
              text('Wygeneruj nowe kody odzyskiwania', 'Replace recovery codes')
            }}</Button
          >
          <p v-if="overviewAction !== 'none'" class="text-sm font-semibold">
            {{ operationLabel }}
          </p>
          <div
            v-if="secret && overviewAction === 'totpConfirm'"
            class="space-y-3 border-l-2 border-[var(--runa-primary-solid)] pl-4"
          >
            <AuthTotpSetup
              :secret="secret"
              :qr-code="qrCode"
              :locale="locale"
            />
            <TextInput
              :model-value="sectionFields.security.enrollment_code ?? ''"
              name="enrollment_code"
              autocomplete="one-time-code"
              inputmode="numeric"
              :label="text('Kod z aplikacji', 'Authenticator code')"
              required
              :error="sectionErrors.security.enrollment_code ?? ''"
              @update:model-value="
                sectionFields.security.enrollment_code = $event ?? '';
                delete sectionErrors.security.enrollment_code;
              "
            />
          </div>
          <AuthAccountProof
            v-if="overviewAction !== 'none'"
            :account="account"
            section="security"
          />
          <template v-if="overviewAction !== 'none'" #actions>
            <Button type="submit" variant="outline" :busy="busy">{{
              operationLabel
            }}</Button>
            <Button :disabled="busy" @click="setAction('none')">{{
              text('Anuluj', 'Cancel')
            }}</Button>
          </template>
        </Form>
      </Card>
    </div>
  </div>
  <ConfirmDialog
    v-model="removeOpen"
    :title="text('Usunąć avatar?', 'Remove avatar?')"
    :confirm-label="text('Usuń avatar', 'Remove avatar')"
    confirm-tone="danger"
    :locale="locale"
    :busy="busy"
    @confirm="confirmRemoval"
  >
    <p class="text-sm leading-7">
      {{
        text(
          'Czy na pewno chcesz usunąć swoje zdjęcie profilowe?',
          'Are you sure you want to remove your profile image?',
        )
      }}
    </p>
    <FormNotifications
      v-if="removeOpen && removalAttempt"
      :attempt="removalAttempt"
      :error="failure ? failureText : ''"
      :invalid="Object.keys(sectionErrors.avatar).length > 0"
      :locale="locale"
    >
      <template #actions>
        <Button v-if="failure === 'csrf'" @click="account.refreshCsrf">{{
          text('Odśwież zabezpieczenie', 'Renew form security')
        }}</Button>
        <Button v-if="failure === 'conflict'" @click="account.initialize">{{
          text('Wczytaj aktualne dane', 'Reload current values')
        }}</Button>
      </template>
    </FormNotifications>
  </ConfirmDialog>
  <Dialog
    :model-value="cropOpen"
    :title="text('Kadrowanie zdjęcia', 'Crop image')"
    :locale="locale"
    size="lg"
    :busy="cropping"
    initial-focus="canvas"
    @update:model-value="closeCrop"
  >
    <FormNotifications :error="cropError" :locale="locale" />
    <AuthAvatarCropper
      v-if="cropOpen && originals[0] && profile"
      ref="cropper"
      :file="originals[0]"
      :locale="locale"
      :max-bytes="Number(profile.capabilities.avatar_max_kib) * 1024"
      @ready="cropReady = $event"
    />
    <template #footer>
      <Button :disabled="cropping" @click="closeCrop(false)">{{
        text('Anuluj', 'Cancel')
      }}</Button>
      <Button
        variant="outline"
        :busy="cropping"
        :disabled="!cropReady"
        @click="applyCrop"
        >{{ text('Zastosuj kadr', 'Apply crop') }}</Button
      >
    </template>
  </Dialog>
</template>
<style scoped>
@media print {
  [data-enrollment-secret] {
    visibility: hidden;
  }
}
</style>
