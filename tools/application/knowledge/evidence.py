"""Bounded, source-verified evidence reads without embedding or index mutation."""

import json
import uuid
from typing import TypedDict

from tools.application.knowledge.contracts import ChunkPayload
from tools.application.knowledge.corpus import digest, read_source, sources
from tools.application.knowledge.ingest import KnowledgeIndexer


class Citation(TypedDict):
    source_path: str
    source_hash: str
    start_line: int | None
    end_line: int | None


class Evidence(TypedDict):
    id: str
    payload: ChunkPayload
    citation: Citation


class EvidenceRead(TypedDict):
    schema_version: int
    collection: str
    chunk_schema_version: int
    results: list[Evidence]
    omitted_chunks: int
    content_characters: int


def citation(payload: ChunkPayload, text: str) -> Citation:
    # Heading context is generated by the parser; only cite a unique literal body.
    prefix = payload["section"] + "\n\n" if payload["section"] else ""
    body = payload["content"].removeprefix(prefix)
    offset = text.find(body)
    unique = bool(body) and offset >= 0 and text.find(body, offset + 1) < 0
    return {
        "source_path": payload["source_path"],
        "source_hash": payload["source_hash"],
        "start_line": text[:offset].count("\n") + 1 if unique else None,
        "end_line": text[: offset + len(body)].count("\n") + 1 if unique else None,
    }


def read(
    indexer: KnowledgeIndexer,
    chunk_id: str,
    *,
    neighbors: int = 0,
    section: bool = False,
    max_chars: int = 12000,
) -> EvidenceRead:
    try:
        if str(uuid.UUID(chunk_id)) != chunk_id:
            raise ValueError
    except (ValueError, AttributeError):
        raise ValueError("Provide a canonical chunk UUID returned by knowledge search.") from None
    if type(neighbors) is not int or not 0 <= neighbors <= 5:
        raise ValueError("Neighbors must be between 0 and 5.")
    if type(max_chars) is not int or not 1000 <= max_chars <= 60000:
        raise ValueError("Evidence budget must be between 1000 and 60000 characters.")
    if indexer.status()["stale"]:
        raise ValueError("Knowledge index is stale/missing/incompatible; run runa:knowledge:index.")
    manifest = indexer.store.manifest()
    points = indexer.store.all_points()
    if manifest is None or manifest.get("pending"):
        raise ValueError("Knowledge write is pending; evidence read refused.")
    payload = points.get(chunk_id)
    if payload is None:
        raise ValueError("Chunk is absent from the current index; search again.")
    root = indexer.context.workspace.root
    allowed = {
        p.relative_to(root).as_posix(): p
        for p in sources(root, indexer.config, context=indexer.context)
    }
    name = payload["source_path"]
    state = manifest["sources"].get(name)
    if name not in allowed or state is None or chunk_id not in state["chunks"]:
        raise ValueError("Chunk is outside the current allowed corpus.")
    text = read_source(allowed[name])
    if digest(text) != state["source_hash"]:
        raise ValueError("Source changed during evidence reading; read refused.")
    ids = state["chunks"]
    position = ids.index(chunk_id)
    selected = set(ids[max(0, position - neighbors) : position + neighbors + 1])
    if section:
        selected.update(key for key in ids if points[key]["section"] == payload["section"])
    # Keep the requested chunk first for budget allocation, emit source order below.
    accepted: set[str] = set()
    size = 0
    for key in [chunk_id, *(key for key in ids if key in selected and key != chunk_id)]:
        point = points[key]
        if (
            point.get("kind") != "chunk"
            or point.get("git_branch") != manifest.get("git_branch")
            or point["source_hash"] != state["source_hash"]
            or point["document_id"] != state["document_id"]
        ):
            raise ValueError("Chunk provenance does not match the current source manifest.")
        length = len(point["content"])
        if size + length <= max_chars:
            accepted.add(key)
            size += length
        elif key == chunk_id:
            raise ValueError("Requested chunk exceeds evidence budget; increase --max-chars.")
    result: EvidenceRead = {
        "schema_version": 1,
        "collection": indexer.config["collection"],
        "chunk_schema_version": indexer.config["schema_version"],
        "results": [
            {"id": key, "payload": points[key], "citation": citation(points[key], text)}
            for key in ids
            if key in accepted
        ],
        "omitted_chunks": len(selected - accepted),
        "content_characters": size,
    }
    if len(json.dumps(result, ensure_ascii=False)) > 256000:
        raise ValueError("Evidence metadata exceeds the response limit; reduce expansion.")
    # Source writers outside the CLI lock may still race; never return known stale data.
    if digest(read_source(allowed[name])) != state["source_hash"] or indexer.status()["stale"]:
        raise ValueError("Knowledge/source changed during evidence reading; retry after indexing.")
    return result
